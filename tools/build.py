# Build fluent/words.js: Oxford list in study order with dictionary data + Persian for all phrases.
import json, random, sys
OUT = sys.argv[1]
ox = json.load(open("ox.json"))
cache = json.load(open("cache_ox.json", encoding="utf-8"))
phr = json.load(open("cache_phr.json", encoding="utf-8"))
import os
wk = json.load(open("cache_wk.json", encoding="utf-8")) if os.path.exists("cache_wk.json") else {}
tr = json.load(open("cache_tr.json", encoding="utf-8")) if os.path.exists("cache_tr.json") else {}
tt = json.load(open("cache_tt.json", encoding="utf-8")) if os.path.exists("cache_tt.json") else {}
WKPOS = {"noun": "noun", "verb": "verb", "adjective": "adjective", "adverb": "adverb", "preposition": "preposition",
         "conjunction": "conjunction", "pronoun": "pronoun", "determiner": "determiner", "exclamation": "interjection", "number": "numeral"}
UK = {"aluminum": "aluminium", "catalog": "catalogue", "councilor": "councillor", "counseling": "counselling",
      "counselor": "counsellor", "endeavor": "endeavour", "enroll": "enrol", "favorable": "favourable", "flavor": "flavour",
      "fulfill": "fulfil", "harbor": "harbour", "liter": "litre", "rumor": "rumour", "skeptical": "sceptical",
      "tumor": "tumour", "fiber": "fibre", "neighboring": "neighbouring"}
SKIP = {"hopefully"}  # already taught as a course chunk
POSMAP = {"noun": "noun", "verb": "verb", "adjective": "adjective", "adverb": "adverb", "preposition": "preposition",
          "conjunction": "conjunction", "pronoun": "pronoun", "determiner": "determiner", "exclamation": "interjection", "number": "numeral"}
def clean(w):
    h = ""
    if " (" in w: w, h = w.split(" (", 1); h = h.rstrip(")")
    while w and w[-1].isdigit(): w = w[:-1]
    return w.strip(), h
stats = {"nodict": [], "nodef": [], "nofa": [], "noaudio": 0}
rows = []
for o in ox:
    w, hint = clean(o["w"])
    if w in SKIP: continue
    c = cache.get(o["w"], {})
    d = c.get("d") or []
    ph = [p for e in d for p in e.get("phonetics", [])]
    uk = next((p for p in ph if p.get("audio", "").endswith("-uk.mp3")), None)
    au = uk or next((p for p in ph if p.get("audio")), None)
    ipa = (uk or {}).get("text") or next((p.get("text") for p in ph if p.get("text")), "") or (d[0].get("phonetic", "") if d else "")
    defs = []
    for pos in dict.fromkeys(o["pos"]):
        ms = [m for e in d for m in e.get("meanings", []) if m.get("partOfSpeech") == POSMAP.get(pos, pos)]
        ds = [x for m in ms for x in m.get("definitions", [])]
        if not ds:
            for wpos, wdefs in wk.get(o["w"], []):
                if wpos == WKPOS.get(pos, pos) and wdefs:
                    defs.append([pos, wdefs[0][0], wdefs[0][1]])
                    if len(wdefs) > 1 and len(o["pos"]) == 1: defs.append([pos, wdefs[1][0], wdefs[1][1]])
                    break
            continue
        ex = ds[0].get("example") or ""
        defs.append([pos, ds[0]["definition"], ex])
        # a second sense only when it looks common: it has its own example and a short definition
        sec = next((x for x in ds[1:5] if x.get("example") and len(x["definition"]) < 130), None)
        if sec and len(defs) < 3 and len(o["pos"]) == 1:
            defs.append([pos, sec["definition"], sec["example"]])
        elif not ex:
            defs[-1][2] = next((x["example"] for x in ds[1:4] if x.get("example")), "")
    if defs and not any(x[2] for x in defs) and tt.get(w):
        defs[0][2] = tt[w][0]
    if not d: stats["nodict"].append(w)
    elif not defs: stats["nodef"].append(w)
    fa = ""
    t = c.get("t") or tr.get(o["w"])
    if t:
        bd = t[1] if len(t) > 1 and isinstance(t[1], list) else []
        parts = []
        for pos in dict.fromkeys(o["pos"]):
            for b in bd:
                if b and b[0] == pos and b[1]:
                    parts.append(", ".join(b[1][:3]))
        fa = " / ".join(parts) or (t[0][0][0] if t[0] else "")
    if not fa: stats["nofa"].append(w)
    if not au: stats["noaudio"] += 1
    rows.append({"w": w, "h": hint, "p": ",".join(o["pos"]), "l": ",".join(o["lv"]), "i": ipa,
                 "a": (au or {}).get("audio", ""), "d": defs, "f": fa, "uk": UK.get(w, "")})
# study order: keep word families together, shuffle families, mix levels
rows.sort(key=lambda r: r["w"].lower())
clusters, cur = [], []
for r in rows:
    if cur and len(cur) < 6 and len(r["w"]) >= 5 and r["w"][:5].lower() == cur[-1]["w"][:5].lower():
        cur.append(r)
    else:
        if cur: clusters.append(cur)
        cur = [r]
clusters.append(cur)
random.Random(5000).shuffle(clusters)
order = [r for c in clusters for r in c]
js = "// Generated by build.py - Oxford 5000 (B2-C1 additions) with dictionary data, and Persian meanings. Do not edit.\n"
js += "COURSE.ox = " + json.dumps(order, ensure_ascii=True, separators=(",", ":")) + ";\n"
js += "COURSE.fa = " + json.dumps(phr, ensure_ascii=True, separators=(",", ":")) + ";\n"
open(OUT, "w", encoding="ascii").write(js)
print(len(order), "words;", len(phr), "phrases;", "no dict:", len(stats["nodict"]), stats["nodict"][:40])
print("no def for pos:", len(stats["nodef"]), stats["nodef"][:40]); print("no fa:", len(stats["nofa"]), "no audio:", stats["noaudio"])
